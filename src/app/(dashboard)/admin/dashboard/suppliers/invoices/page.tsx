"use client";

import {
  Eye
} from "lucide-react";


import Link from "next/link";
import { useMemo, useState } from "react";
import { Button, Select, Tag } from "antd";

import PageHeader from "@/components/shared/page-header";
import { DataTable, type Column } from "@/components/shared/data-table";
import { adminBreadcrumb } from "@/config/breadcrumb.config";
import { useActiveBusinessId } from "@/hooks/use-active-business";
import { useSupplierInvoicesQuery } from "@/lib/api";
import type { SupplierInvoice } from "@/types/suppliers/return";
import type { SupplierInvoiceStatus } from "@/lib/api";

const statusColor: Record<SupplierInvoiceStatus, string> = {
  CANCELLED: "default",
  PAID: "green",
  PARTIALLY_PAID: "blue",
  UNPAID: "orange",
};

function money(value: string | number | null | undefined) {
  return `BDT ${Number(value ?? 0).toLocaleString()}`;
}

export default function SupplierInvoicesPage() {
  const businessId = useActiveBusinessId();
  const [page, setPage] = useState(1);
  const [search, setSearch] = useState("");
  const [status, setStatus] = useState<SupplierInvoiceStatus | undefined>();

  const query = useMemo(
    () => ({ page, limit: 10, search, status }),
    [page, search, status],
  );
  const invoices = useSupplierInvoicesQuery(businessId ?? "", query);

  const columns: Column<SupplierInvoice>[] = [
    {
      key: "invoiceNo",
      label: "Invoice",
      type: "primary",
      render: (invoice) => (
        <Link href={`/admin/dashboard/suppliers/invoices/${invoice.id}`}>
          {invoice.invoiceNo}
        </Link>
      ),
    },
    {
      key: "supplier",
      label: "Supplier",
      render: (invoice) => invoice.supplier?.name ?? invoice.supplierId,
    },
    {
      key: "totalAmount",
      label: "Total",
      render: (invoice) => money(invoice.totalAmount),
    },
    {
      key: "paidAmount",
      label: "Paid",
      render: (invoice) => money(invoice.paidAmount),
    },
    {
      key: "status",
      label: "Status",
      type: "meta",
      render: (invoice) => (
        <Tag color={statusColor[invoice.status]}>{invoice.status}</Tag>
      ),
    },
  ];

  return (
    <div className="space-y-6">
      <PageHeader
        title="Supplier Invoices"
        subtitle="Review purchase invoices generated by supplier workflows."
        breadcrumb={adminBreadcrumb}
      />

      <DataTable
        data={invoices.data?.items ?? []}
        columns={columns}
        loading={invoices.isLoading || invoices.isFetching}
        onSearch={(value) => {
          setSearch(value);
          setPage(1);
        }}
        extra={
          <Select
            allowClear
            placeholder="Status"
            value={status}
            style={{ width: 170 }}
            onChange={(value) => {
              setStatus(value);
              setPage(1);
            }}
            options={["UNPAID", "PARTIALLY_PAID", "PAID", "CANCELLED"].map(
              (item) => ({ label: item, value: item }),
            )}
          />
        }
        actions={(invoice) => (
          <Link href={`/admin/dashboard/suppliers/invoices/${invoice.id}`}>
            <Button icon={<Eye />} />
          </Link>
        )}
        pagination={{
          currentPage: page,
          totalPages: invoices.data?.meta.totalPages ?? 1,
          onPageChange: setPage,
        }}
      />
    </div>
  );
}
